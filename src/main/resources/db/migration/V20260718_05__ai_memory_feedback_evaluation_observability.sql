CREATE TABLE IF NOT EXISTS ai_conversation (
    id VARCHAR(64) PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    workspace_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    session_id VARCHAR(128) NOT NULL,
    agent_id VARCHAR(64) NOT NULL,
    agent_version INT NOT NULL,
    title VARCHAR(512) NULL,
    status VARCHAR(32) NOT NULL,
    last_message_at TIMESTAMP(3) NULL,
    created_by VARCHAR(64) NOT NULL,
    updated_by VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    UNIQUE KEY uk_ai_conversation_session (tenant_id, workspace_id, user_id, agent_id, session_id),
    KEY idx_ai_conversation_owner (tenant_id, workspace_id, user_id, last_message_at, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

